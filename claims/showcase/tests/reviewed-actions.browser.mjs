/** Exercise the installed showcase across Chat and Reviews without filing a test note in Juris. */
import assert from 'node:assert/strict'
import {createRequire} from 'node:module'
import {pickEmployee} from '../../auth/tests/picker.mjs'
const {chromium}=createRequire(new URL('../../../apps/web/package.json',import.meta.url))('playwright')
const origin=new URL(process.env.CLAIMS_APP_ORIGIN || 'http://127.0.0.1:3180')
assert.ok(['localhost','127.0.0.1'].includes(origin.hostname))
const browser=await chromium.launch({channel:'chrome'})
const claim='CLM-000020'
const text='Synthetic handling review '+Date.now()
const button=(root,name)=>root.getByRole('button',{name,exact:true})
try {
  const page=await browser.newPage({viewport:{width:1360,height:900}})
  page.setDefaultTimeout(25000)
  await page.goto(new URL('/open-workbench',origin).href)
  await pickEmployee(page,'cms-adjuster-01')
  const open=page.getByRole('button',{name:/^Open CLM-000020\b/})
  await open.click()
  await button(page,'JURIS record').click()
  await page.getByRole('heading',{name:'Claim notes'}).waitFor()
  const snapshot=async()=> {
    const r=await page.request.get(new URL('/claims/api/items/'+claim+'/juris',origin).href)
    assert.ok(r.ok());return r.json()
  }
  const before=await snapshot()
  await button(page,'Ask agent').click()
  const drawer=page.locator('.cc-drawer:visible')
  await drawer.getByRole('textbox').fill('Create a note: '+text)
  await drawer.getByRole('textbox').press('Enter')
  const card=drawer.locator('article.cw-entry').filter({hasText:text})
  await button(card,'Approve and add note').waitFor()
  assert.equal((await snapshot()).revision,before.revision)
  await button(card,'Edit draft').click()
  await drawer.getByLabel('Note text').fill(text+' edited')
  await button(drawer,'Prepare for review').click()
  await drawer.locator('article.cw-entry').filter({hasText:text+' edited'}).waitFor()
  await button(drawer,'Collapse').click()
  await button(page,'Reviews').click()
  const review=page.locator('article.cw-entry').filter({hasText:text+' edited'})
  await button(review,'Discard').click()
  await review.getByText(/rejected/).waitFor()
  await button(page,'Schedule callback or diary').click()
  await page.getByLabel('Due date and time (local)').waitFor()
  assert.equal((await snapshot()).revision,before.revision)
  await button(page,'Cancel editing').click()
  await page.setViewportSize({width:720,height:800})
  assert.equal(await page.locator('.claim-action-review:visible').last().evaluate(e=>e.scrollWidth<=e.clientWidth+2),true)
  await page.setViewportSize({width:1360,height:900})
  await button(page,'Ask agent').click()
  await page.getByText('Open in Chat',{exact:true}).last().click()
  const composer=page.locator('[data-composer-card]:visible')
  await button(composer,'Remove '+claim).waitFor()
  const editor=composer.locator('[contenteditable=true]')
  await editor.fill('Show the handling priority for '+claim)
  await editor.press('Enter')
  await page.getByText('Handling priority · '+before.handlingPriority,{exact:false}).last().waitFor()
  const followup=page.locator('.claim-action-review:visible').last()
  await button(followup,'Update handling field').click()
  await followup.getByLabel('Proposed value').waitFor()
  await button(followup,'Cancel editing').click()
  assert.equal((await snapshot()).revision,before.revision)
  console.log('PASS native Chat confirmed reads and contextual follow-ups, typed draft, edited review across surfaces, rejection, callback editor, responsive layout and unchanged Juris revision')
} finally {await browser.close()}
